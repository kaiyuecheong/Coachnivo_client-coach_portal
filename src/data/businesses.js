export const getBusinessPlan = (planId) => BUSINESS_PLANS.find((plan) => plan.id === planId) || BUSINESS_PLANS[0];

export function getBusinessLaunchProgress(business) {
  const checklist = business?.launchChecklist || {};
  const values = Object.values(checklist);
  const complete = values.filter(Boolean).length;
  return { complete, total: values.length, percent: values.length ? Math.round((complete / values.length) * 100) : 0, ready: values.length > 0 && complete === values.length };
}

